"""SWI-Prolog, run as a separate program.

We never link to the engine. There is no compiled Python binding, no shared
library loading and no version pinning between Python and Prolog. We write two
files, run swipl, and read JSON back from its standard output.

The consequence worth knowing is that the path to swipl.exe is just a value we
control, so the engine can live inside the project rather than being installed
system-wide.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import tempfile
import time
from pathlib import Path

from ..core.ast import (
    Clause,
    Literal,
    format_clause,
    format_literal,
    format_term,
)
from .base import (
    Answer,
    Capabilities,
    Justification,
    Program,
    Solution,
    SolveOpts,
    Status,
)

META_INTERPRETER = Path(__file__).resolve().parent / "meta.pl"

INSTALL_HINT = (
    "Install it -- winget install SWI-Prolog.SWI-Prolog on Windows, "
    "brew install swi-prolog on macOS, apt install swi-prolog on Debian or "
    "Ubuntu -- or set LOGICLAYER_SWIPL to the full path of the swipl executable."
)


class EngineNotFound(RuntimeError):
    pass


def find_swipl(explicit: str | os.PathLike[str] | None = None) -> Path | None:
    """Locate the engine.

    In order: an explicit path, then the LOGICLAYER_SWIPL setting, then the
    standard Windows install folder, then whatever `swipl` is on the PATH.

    The Windows folder is checked because the SWI-Prolog installer there does
    not always add itself to the PATH. A package manager install on Linux or
    macOS always does, so the PATH covers those.
    """
    candidates: list[Path] = []
    if explicit:
        candidates.append(Path(explicit))
    if env := os.environ.get("LOGICLAYER_SWIPL"):
        candidates.append(Path(env))
    if os.name == "nt":
        program_files = os.environ.get("PROGRAMFILES", r"C:\Program Files")
        candidates.append(Path(program_files) / "swipl" / "bin" / "swipl.exe")

    for candidate in candidates:
        if candidate.is_file():
            return candidate

    found = shutil.which("swipl")
    return Path(found) if found else None


def _prolog_path(path: Path) -> str:
    """Prolog reads a backslash as an escape, so use forward slashes even on
    Windows. SWI accepts them."""
    return str(path).replace("\\", "/")


def render_program(program: Program) -> str:
    """The program as SWI-Prolog source.

    Three parts, and each is needed:

    Dynamic declarations for every predicate mentioned anywhere, including ones
    that are referred to but never defined. Without them, `\\+ rough(anne)`
    raises "unknown procedure" instead of quietly failing, which would break
    the closed-world assumption the whole thing depends on.

    The clauses themselves, so a goal can be called directly when no proof is
    wanted. That path is much faster than meta-interpretation.

    An ll_src/3 table pairing each clause with its ledger id, which is what the
    meta-interpreter walks. It is how the ledger id reaches the proof tree.
    """
    mentioned: dict[str, None] = {}
    for sourced in program.clauses:
        for predicate in sourced.clause.predicates():
            mentioned.setdefault(predicate, None)

    lines = [
        "% Generated by Logic Layer. Do not edit.",
        "",
        "% Every predicate is declared dynamic, including ones nothing defines,",
        "% so an unproven goal fails quietly instead of raising an error.",
    ]
    lines += [f":- dynamic {name}." for name in mentioned]
    lines.append("")

    lines.append("% The clauses, for calling directly when no proof is needed.")
    for sourced in program.clauses:
        lines.append(f"% [{sourced.id}]")
        lines.append(format_clause(sourced.clause))
    lines.append("")

    lines.append("% Clause table for the meta-interpreter: head, body, ledger id.")
    for sourced in program.clauses:
        lines.append(_ll_src_fact(sourced.id, sourced.clause))
    lines.append("")

    return "\n".join(lines)


def _ll_src_fact(entry_id: str, clause: Clause) -> str:
    head = format_term(clause.head)
    if clause.is_fact:
        body = "true"
    else:
        body = ", ".join(format_literal(lit) for lit in clause.body)
        if len(clause.body) > 1:
            body = f"({body})"
    return f"ll_src({head}, {body}, '{entry_id}')."


def _to_justification(node: dict | None) -> Justification | None:
    if not node:
        return None
    return Justification(
        goal=node["goal"],
        kind=node["kind"],
        clause_id=node.get("id"),
        children=tuple(filter(None, (_to_justification(c) for c in node.get("children", ())))),
        # Only negation nodes carry this. Anything else is ground by definition,
        # since it was proved rather than assumed.
        ground=bool(node.get("ground", True)),
    )


class SwiPrologPort:
    """Drives SWI-Prolog through its command line."""

    def __init__(self, binary: str | os.PathLike[str] | None = None) -> None:
        found = find_swipl(binary)
        if found is None:
            raise EngineNotFound(f"SWI-Prolog not found. {INSTALL_HINT}")
        self.binary = found
        self._version: str | None = None

    def version(self) -> str:
        if self._version is None:
            proc = subprocess.run(
                [str(self.binary), "--version"],
                capture_output=True,
                text=True,
                timeout=15,
                stdin=subprocess.DEVNULL,
            )
            self._version = proc.stdout.strip() or "unknown"
        return self._version

    def capabilities(self) -> Capabilities:
        return Capabilities(
            name="swi-prolog",
            version=self.version(),
            naf=True,
            # Prolog can only fail to prove something. It can never establish
            # that a goal is false, so it never returns DISPROVED. s(CASP) will.
            classical_negation=False,
            function_symbols=True,
            # No proof tree of its own; ours comes from meta.pl.
            native_justification=False,
            # Left-recursive rules loop forever. Hence the mandatory timeout.
            guaranteed_termination=False,
        )

    def solve(self, program: Program, goal: Literal, opts: SolveOpts) -> Solution:
        started = time.perf_counter()

        with tempfile.TemporaryDirectory(prefix="logiclayer-") as workspace:
            work = Path(workspace)
            kb_file = work / "kb.pl"
            request_file = work / "request.json"

            kb_file.write_text(render_program(program), encoding="utf-8")
            request_file.write_text(
                json.dumps(
                    {
                        "kb": _prolog_path(kb_file),
                        "goal": format_literal(goal),
                        "limit": opts.max_solutions,
                        "proof": opts.want_proof,
                    }
                ),
                encoding="utf-8",
            )

            argv = [
                str(self.binary),
                "-q",
                "--no-tty",
                "-g",
                f"ll_main('{_prolog_path(request_file)}')",
                "-t",
                "halt",
                _prolog_path(META_INTERPRETER),
            ]

            try:
                proc = subprocess.run(
                    argv,
                    capture_output=True,
                    text=True,
                    timeout=opts.timeout,
                    # Prolog must never wait for input. Closing stdin turns a
                    # stray prompt into an immediate failure instead of a hang.
                    stdin=subprocess.DEVNULL,
                )
            except subprocess.TimeoutExpired:
                return Solution(
                    status=Status.ERROR,
                    engine="swi-prolog",
                    duration_ms=self._elapsed(started),
                    message=(
                        f"the engine did not finish within {opts.timeout}s and was stopped. "
                        "A rule that refers to itself before narrowing the problem down will "
                        "loop forever in Prolog."
                    ),
                )

        return self._read_result(proc, started, checked=opts.want_proof)

    # -- turning the engine's output into a Solution ------------------------

    def _read_result(
        self, proc: subprocess.CompletedProcess[str], started: float, *, checked: bool
    ) -> Solution:
        elapsed = self._elapsed(started)
        output = proc.stdout.strip()

        if not output:
            return Solution(
                status=Status.ERROR,
                engine="swi-prolog",
                duration_ms=elapsed,
                message=_clean_stderr(proc.stderr) or f"the engine produced no output (exit {proc.returncode})",
            )

        try:
            payload = json.loads(output)
        except json.JSONDecodeError:
            return Solution(
                status=Status.ERROR,
                engine="swi-prolog",
                duration_ms=elapsed,
                message=f"could not read the engine's output: {output[:400]}",
            )

        if payload["status"] == "error":
            return Solution(
                status=Status.ERROR,
                engine="swi-prolog",
                duration_ms=elapsed,
                message=payload.get("message") or _clean_stderr(proc.stderr),
            )

        answers = tuple(
            Answer(
                bindings=item.get("bindings") or {},
                justification=_to_justification(item.get("proof")),
            )
            for item in payload["answers"]
        )

        # No answers means no proof was found. Plain Prolog cannot tell that
        # apart from the goal being false, so we must report UNKNOWN and not
        # DISPROVED. An engine with real negation would distinguish them.
        status = Status.PROVED if answers else Status.UNKNOWN

        return Solution(
            status=status,
            answers=answers,
            engine="swi-prolog",
            duration_ms=elapsed,
            truncated=bool(payload.get("truncated")),
            assumptions_checked=checked,
            message=(
                f"stopped after {len(answers)} answers; there are more"
                if payload.get("truncated")
                else None
            ),
        )

    @staticmethod
    def _elapsed(started: float) -> float:
        return round((time.perf_counter() - started) * 1000, 2)


def _clean_stderr(text: str) -> str:
    """Prolog's diagnostics are terse and repetitive. Keep the useful lines."""
    lines = [line.strip() for line in (text or "").splitlines() if line.strip()]
    keep = [line for line in lines if not line.startswith("ERROR:   ")]
    return " ".join(keep[:4])
